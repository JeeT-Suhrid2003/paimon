"""
Automated Demo Recorder for Paimon Chat.
Runs Paimon Companion GUI and terminal chat simulation under Xvfb,
records a video (MP4) and an animated GIF, and saves her beautiful TTS voice.
"""
import os
import sys
import time
import shutil
import subprocess

# Add current directory to path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gui
import audio
import config

print("==================================================")
print("🚀 STARTING AUTOMATED PAIMON COMPANION DEMO RECORDER")
print("==================================================")

# Ensure output directories exist
os.makedirs("demo_assets", exist_ok=True)
os.makedirs("demo_screenshots", exist_ok=True)

# Clean up prior recordings
for name in ["paimon_demo.mp4", "paimon_demo.gif"]:
    path = os.path.join("demo_assets", name)
    if os.path.exists(path):
        try:
            os.remove(path)
        except Exception as e:
            print(f"Error cleaning up {path}: {e}")

# Track FFMPEG process
ffmpeg_proc = None

def capture_screenshot(name):
    """Capture the virtual screen using scrot."""
    filepath = f"demo_screenshots/{name}.png"
    try:
        # Capture the screen (Xvfb is configured to 320x320)
        subprocess.run(["scrot", "-z", filepath], check=True)
        # Copy to demo_assets
        shutil.copy(filepath, f"demo_assets/{name}.png")
        print(f"📸 [Screenshot] Captured {name}.png successfully!")
    except Exception as e:
        print(f"❌ [Screenshot Error] Failed to capture {name}: {e}")

def save_voice_file(name):
    """Copy the latest temporary WAV file generated by audio.py."""
    try:
        # Give a small window for the async speech to write the WAV file
        time.sleep(0.5)
        with audio._temp_lock:
            if audio._temp_files:
                latest_temp = audio._temp_files[-1]
                dest = f"demo_assets/{name}.wav"
                shutil.copy(latest_temp, dest)
                print(f"🎵 [Audio Saved] Saved {name}.wav successfully!")
            else:
                print(f"⚠️ [Audio Warning] No temporary audio files found for {name}")
    except Exception as e:
        print(f"❌ [Audio Copy Error] Failed to copy audio for {name}: {e}")

# Conversation steps mapped to Tkinter timers
def welcome_step():
    print("\n🧚 Paimon has floated into the chat! (Type 'exit' to leave)")
    welcome_text = "Oh! Hey Traveler! Paimon was getting super bored waiting around for you!"
    print(f"Paimon: {welcome_text}")
    gui.update_image("happy")
    audio.generate_and_play_speech(welcome_text)

    # Take screenshot and save audio after rendering/generation
    gui.get_root().after(1800, lambda: [capture_screenshot("01_welcome"), save_voice_file("paimon_welcome")])

def thinking_step():
    print("\nYou: Hey Paimon, what are you thinking about?")
    print("Paimon: ", end="", flush=True)
    gui.update_image("thinking")

    thinking_text = "Oh! Paimon was just thinking about how much she wants a huge plate of sticky honey roast!"
    print(thinking_text)
    audio.generate_and_play_speech(thinking_text)

    gui.get_root().after(1800, lambda: [capture_screenshot("02_thinking"), save_voice_file("paimon_thinking")])

def sad_step():
    print("\nYou: Paimon, bad news... we ran out of Mora and there are no snacks left.")
    print("Paimon: ", end="", flush=True)
    gui.update_image("sad")

    sad_text = "What?! No snacks?! Paimon is gonna starve to death! This is an absolute emergency!"
    print(sad_text)
    audio.generate_and_play_speech(sad_text)

    gui.get_root().after(1800, lambda: [capture_screenshot("03_sad"), save_voice_file("paimon_sad")])

def happy_trigger_step():
    print("\nYou: Just kidding! I finished the quest, and we got tons of sweet Madame and Mora!")
    print("Paimon: ", end="", flush=True)
    gui.update_image("happy")

    happy_text = "Yay! Paimon knew she could count on you! You're the best Traveler ever!"
    print(happy_text)
    audio.generate_and_play_speech(happy_text)

    gui.get_root().after(1800, lambda: [capture_screenshot("04_happy"), save_voice_file("paimon_happy")])

def exit_step():
    print("\nYou: exit")
    farewell_text = "Aww, leaving already? Bring tasty snacks next time!"
    print(f"Paimon: {farewell_text}")
    gui.update_image("sad")
    audio.generate_and_play_speech(farewell_text)

    gui.get_root().after(1800, lambda: [capture_screenshot("05_exit"), save_voice_file("paimon_goodbye")])

def shutdown_step():
    print("\n🛑 Simulation finished. Closing GUI and terminating recorder...")
    gui.quit_app()

def main():
    global ffmpeg_proc

    # Initialize all modules
    audio.initialize_audio()
    gui.init_gui()

    display = os.environ.get("DISPLAY", ":99")
    print(f"Recording virtual desktop on DISPLAY {display}...")

    # Start FFMPEG screen recording
    ffmpeg_proc = subprocess.Popen([
        "ffmpeg", "-y",
        "-f", "x11grab",
        "-draw_mouse", "0",
        "-video_size", "320x320",
        "-i", display,
        "-codec:v", "libx264",
        "-r", "15",
        "-pix_fmt", "yuv420p",
        "demo_assets/paimon_demo.mp4"
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    # Wait briefly for FFMPEG to initialize
    time.sleep(1)

    # Schedule the steps
    root = gui.get_root()
    root.after(500, welcome_step)
    root.after(4500, thinking_step)
    root.after(8500, sad_step)
    root.after(12500, happy_trigger_step)
    root.after(16500, exit_step)
    root.after(20500, shutdown_step)

    # Start the event loop (blocking call until quit_app)
    gui.run_mainloop()

    # Terminate FFMPEG gracefully
    if ffmpeg_proc:
        print("Stopping FFMPEG screen recording...")
        ffmpeg_proc.terminate()
        try:
            ffmpeg_proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            ffmpeg_proc.kill()

    # Post-process: Compile the MP4 video into an animated GIF
    print("Generating optimized animated GIF...")
    subprocess.run([
        "ffmpeg", "-y",
        "-i", "demo_assets/paimon_demo.mp4",
        "-vf", "fps=10,scale=320:-1:flags=lanczos,split[s0][s1];[s0]palettegen[p];[s1][p]paletteuse",
        "demo_assets/paimon_demo.gif"
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    print("\n==================================================")
    print("✨ DEMO ASSETS CREATED SUCCESSFULLY!")
    print("Check out the files inside 'demo_assets/':")
    print("  - paimon_demo.mp4 (Screen recording video)")
    print("  - paimon_demo.gif (Animated expression showcase)")
    print("  - paimon_welcome.wav, paimon_thinking.wav, etc. (Voice clips)")
    print("==================================================")

    # Clean up audio temp files
    audio.cleanup_audio_files()

if __name__ == "__main__":
    main()
